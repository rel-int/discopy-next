"""Print the review threads of a pull request, trimmed, or the TODO.md text of a round.

Usage: threads.py <pr> [--all] [--reviews] [--todo FILE] [--repo owner/name]
"""

import argparse
import json
import os
import re
import ssl
import sys
import urllib.error
import urllib.request

API = "https://api.github.com"
CUBIC = "cubic-dev-ai[bot]"
CAPPED = 250
DROPPED_DETAILS = re.compile(
    r"prompt|ai agent|analysis chain|learnings|fingerprint|review details|"
    r"additional comments|tools|walkthrough|finishing touches",
    re.I,
)
FOOTERS = re.compile(
    r"\n-{3,}\s*\n\s*(_Generated by|🤖 Generated with|Generated by Codex|"
    r"Generated by Amp).*",
    re.S,
)


def context():
    for name in ("SSL_CERT_FILE", "REQUESTS_CA_BUNDLE"):
        path = os.environ.get(name)
        if path and os.path.exists(path):
            return ssl.create_default_context(cafile=path)
    return ssl.create_default_context()


def fetch(url, ctx):
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "cubic-round",
    }
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, context=ctx, timeout=30) as response:
        return json.load(response), 'rel="next"' in response.headers.get(
            "Link", ""
        )


def get_all(path, ctx):
    result, number, more = [], 1, True
    while more:
        separator = "&" if "?" in path else "?"
        page, more = fetch(
            f"{API}{path}{separator}per_page=100&page={number}", ctx
        )
        if not isinstance(page, list):
            return page
        result, number = result + page, number + 1
    return result


def strip_details(body):
    pattern = re.compile(
        r"<details>\s*<summary>(.*?)</summary>((?:(?!<details>).)*?)</details>",
        re.S | re.I,
    )
    while True:
        match = pattern.search(body)
        if not match:
            return body
        summary, inside = match.groups()
        kept = "" if DROPPED_DETAILS.search(summary) else inside
        body = body[: match.start()] + kept + body[match.end() :]


def trim(body):
    body = re.sub(r"<!--.*?-->", "", body or "", flags=re.S)
    body = strip_details(body)
    body = FOOTERS.sub("", body)
    body = re.sub(r"<img[^>]*alt=\"([^\"]*)\"[^>]*>", r"[\1]", body)
    body = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"[\1]", body)
    body = re.sub(
        r"✅ Addressed in \[`([0-9a-f]{7,40})`\]\([^)]*\)",
        lambda m: f"✅ addressed in {m.group(1)[:8]}",
        body,
    )
    body = re.sub(r"<sub>.*?</sub>", "", body, flags=re.S)
    body = "\n".join(
        line
        for line in body.splitlines()
        if not re.search(r"Fix (all )?with cubic|cubic\.dev/", line)
    )
    body = re.sub(r"\[([^\]]+)\]\(https?://[^)]*\)", r"\1", body)
    body = re.sub(r"</?(sub|sup|b|strong|em|br|p|div)\s*/?>", "", body)
    body = re.sub(r"^(P\d):\s*", r"[\1] ", body.strip())
    return re.sub(r"\n{3,}", "\n\n", body).strip()


def one_line(body, width=200):
    text = " ".join(trim(body).split())
    return text if len(text) <= width else text[: width - 1] + "…"


def gist(body, width=110):
    text = re.sub(r"^\[P\d\]\s*", "", " ".join(trim(body).split()))
    text = re.sub(r"```suggestion.*", "", text).strip()
    first = (
        re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
        or "apply the suggestion"
    )
    return first if len(first) <= width else first[: width - 1] + "…"


def threads_of(repo, pr, comments, ctx):
    by_id = {c["id"]: c for c in comments}
    try:
        raw = get_all(f"/repos/{repo}/pulls/{pr}/ccr/review_threads", ctx)
    except (urllib.error.URLError, OSError):
        raw = None
    if isinstance(raw, list):
        return [
            dict(
                t, comments=[by_id[i] for i in t["comment_ids"] if i in by_id]
            )
            for t in raw
            if any(i in by_id for i in t["comment_ids"])
        ]
    roots = {}
    for comment in comments:
        root = comment.get("in_reply_to_id") or comment["id"]
        roots.setdefault(root, []).append(comment)
    return [
        {
            "resolved": None,
            "outdated": c[0]["line"] is None,
            "path": c[0]["path"],
            "line": c[0]["line"],
            "comments": c,
        }
        for c in roots.values()
    ]


def reviewed_sha(review):
    marker = re.search(
        r"cubic:review-post:[^:]*:([0-9a-f]{40}):", review["body"] or ""
    )
    return marker.group(1) if marker else review["commit_id"]


def cubic_status(repo, pr, head, reviews, ctx):
    ours = [r for r in reviews if r["user"]["login"] == CUBIC]
    if not ours:
        return "cubic: no review yet"
    last = ours[-1]
    reviewed = reviewed_sha(last)
    status = f"cubic: last review {last['state']} on {reviewed[:8]}"
    if head == reviewed:
        return status + " = head"
    commits = get_all(f"/repos/{repo}/pulls/{pr}/commits", ctx)
    parents = {c["sha"]: [p["sha"] for p in c["parents"]] for c in commits}
    sha, code = head, []
    while sha in parents and sha != reviewed:
        if len(parents[sha]) < 2:
            code.append(sha[:8])
        sha = parents[sha][0]
    if sha != reviewed and len(commits) < CAPPED:
        return status + f", not on the branch of head {head[:8]} (force-push?)"
    count = f"{len(code)}" if sha == reviewed else f">={len(code)}"
    if code:
        return status + (
            f"; {count} code commit(s) since ({', '.join(code[:5])}),"
            " not re-reviewed yet"
        )
    return status + f"; only merges since, head {head[:8]} (cubic skips those)"


def review_states(reviews):
    latest = {}
    for review in reviews:
        if review["state"] != "COMMENTED" or trim(review["body"]):
            latest[review["user"]["login"]] = review
    return (
        ", ".join(
            f"{login} {r['state']}@{reviewed_sha(r)[:8]}"
            for login, r in latest.items()
        )
        or "none"
    )


def where(thread):
    line = thread["line"] or thread["comments"][0].get("original_line")
    return thread["path"] + (f":{line}" if line else "")


def unanswered(thread):
    return (
        thread["comments"][-1]["user"]["login"]
        == thread["comments"][0]["user"]["login"]
    )


def bot(thread):
    return thread["comments"][0]["user"]["login"].endswith("[bot]")


def ours(thread):
    return not thread["resolved"] and (unanswered(thread) or bot(thread))


def header(thread, n):
    root = thread["comments"][0]
    flags = "".join(
        f" [{f}]" for f in ("resolved", "outdated") if thread.get(f)
    )
    if not thread.get("resolved") and not unanswered(thread):
        flags += (
            " [answered, resolve it]"
            if bot(thread)
            else (f" [answered, waits on {root['user']['login']}]")
        )
    return f"{n}. {where(thread)} [{root['user']['login']}] thread-root-id={root['id']}{flags}"


def block(thread, n):
    root, *replies = thread["comments"]
    body = trim(root["body"])
    addressed = re.search(r"\s*✅ addressed in (\w+)$", body)
    title = header(thread, n)
    if addressed:
        body, title = (
            body[: addressed.start()],
            f"{title} [addressed {addressed.group(1)}]",
        )
    lines = [title, body]
    lines += [
        f"  ↳ {r['user']['login']}: {one_line(r['body'])}" for r in replies
    ]
    return "\n".join(lines)


def todo(pr, pull, shown):
    authors = sorted({t["comments"][0]["user"]["login"] for t in shown})
    quoted = [
        f"Review round on #{pr} ({', '.join(authors)}), head {pull['head']['sha'][:8]}:"
    ]
    for n, thread in enumerate(shown, 1):
        quoted += [
            "",
            f"{n}. {where(thread)} (thread {thread['comments'][0]['id']})",
        ]
        quoted += trim(thread["comments"][0]["body"]).splitlines()
    feedback = (
        "\n".join("> " + line if line else ">" for line in quoted) + "\n"
    )
    boxes = "".join(
        f"{where(t)} {gist(t['comments'][0]['body'])}\n" for t in shown
    )
    return feedback, boxes


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("pr", type=int)
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--reviews", action="store_true")
    parser.add_argument("--todo", metavar="FILE")
    parser.add_argument("--repo", default="rel-int/discopy-next")
    args = parser.parse_args()
    ctx = context()
    try:
        pull = fetch(f"{API}/repos/{args.repo}/pulls/{args.pr}", ctx)[0]
        comments = get_all(f"/repos/{args.repo}/pulls/{args.pr}/comments", ctx)
        reviews = get_all(f"/repos/{args.repo}/pulls/{args.pr}/reviews", ctx)
        threads = threads_of(args.repo, args.pr, comments, ctx)
        status = cubic_status(
            args.repo, args.pr, pull["head"]["sha"], reviews, ctx
        )
    except (urllib.error.URLError, OSError) as error:
        sys.exit(f"threads.py: {error}")
    open_threads = [t for t in threads if not t["resolved"]]
    if args.todo:
        pending = [t for t in open_threads if unanswered(t)]
        if not pending:
            sys.exit(
                "threads.py: no unresolved thread waits on an answer, no TODO.md needed"
            )
        feedback, boxes = todo(args.pr, pull, pending)
        with open(args.todo, "w", encoding="utf-8") as file:
            file.write(feedback)
        print(boxes, end="")
        return
    print(
        f"#{args.pr} {pull['state']}{' merged' if pull.get('merged') else ''}"
        f" head={pull['head']['sha'][:8]} {pull['title'][:70]}"
    )
    print(status)
    print(f"reviews: {review_states(reviews)}")
    print(
        f"threads: {len(threads)}, unresolved {len(open_threads)},"
        f" on us {sum(map(ours, open_threads))}"
        + (
            " (ccr route failed: resolution unknown)"
            if any(t["resolved"] is None for t in threads)
            else ""
        )
    )
    if args.reviews:
        for review in reviews:
            body = trim(review["body"])
            if body:
                print(
                    f"\nreview {review['id']} {review['user']['login']}"
                    f" {review['state']}@{reviewed_sha(review)[:8]}\n{body}"
                )
    for n, thread in enumerate(threads if args.all else open_threads, 1):
        full = args.all or ours(thread)
        print(("\n" + block(thread, n)) if full else header(thread, n))


if __name__ == "__main__":
    main()
